def _cached_record(key, factory):
    """Memoize processed records used by the viewport overlay.

    Labels are rebuilt on every viewport redraw, and a plane record runs an
    iterative eigen decomposition, so an unmemoized overlay cost one solve per
    polygon per frame.
    """
    record = _record_cache.get(key)
    if record is not None:
        return record
    record = factory()
    if record is not None:
        if len(_record_cache) >= RECORD_CACHE_LIMIT:
            _record_cache.clear()
        _record_cache[key] = record
    return record


def clear_record_cache():
    _record_cache.clear()


