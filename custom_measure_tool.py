def ensure_measure_overlay():
    global _overlay_handle_3d, _overlay_handle_2d
    if _overlay_handle_3d is None:
        _overlay_handle_3d = bpy.types.SpaceView3D.draw_handler_add(
            _draw_measurements_3d,
            (),
            'WINDOW',
            'POST_VIEW',
        )
    if _overlay_handle_2d is None:
        _overlay_handle_2d = bpy.types.SpaceView3D.draw_handler_add(
            _draw_measurements_2d,
            (),
            'WINDOW',
            'POST_PIXEL',
        )


def remove_measure_overlay():
    global _overlay_handle_3d, _overlay_handle_2d
    if _overlay_handle_3d is not None:
        bpy.types.SpaceView3D.draw_handler_remove(_overlay_handle_3d, 'WINDOW')
        _overlay_handle_3d = None
    if _overlay_handle_2d is not None:
        bpy.types.SpaceView3D.draw_handler_remove(_overlay_handle_2d, 'WINDOW')
        _overlay_handle_2d = None
    reset_tool_state()


def overlay_is_active():
    return _overlay_handle_3d is not None and _overlay_handle_2d is not None


def reset_tool_state():
    """Drop every piece of state that belongs to the previous .blend file.

    The preview dictionaries and the record cache live at module level, so
    without this a freshly loaded file inherits the ghost preview and the
    cached geometry of the file that was open before.
    """
    _reset_preview()
    _reset_polygon_preview()
    clear_record_cache()


