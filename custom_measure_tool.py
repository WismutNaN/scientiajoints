def _segments(points, closed=False):
    if len(points) == 2:
        return ((points[0], points[1]),)
    segments = [(points[index], points[index + 1]) for index in range(len(points) - 1)]
    if closed and len(points) >= 3:
        segments.append((points[-1], points[0]))
    return tuple(segments)


def _distance_to_segment_2d(point, start, end):
    segment = end - start
    length_squared = segment.length_squared
    if length_squared == 0:
        return (point - start).length
    factor = max(0.0, min(1.0, (point - start).dot(segment) / length_squared))
    projection = start + segment * factor
    return (point - projection).length


def _closest_point_on_segment(point, start, end):
    segment = end - start
    length_squared = segment.length_squared
    if length_squared <= 0:
        return start.copy()
    factor = max(0.0, min(1.0, (point - start).dot(segment) / length_squared))
    return start + segment * factor


def _average_point(points):
    if not points:
        return None
    total = points[0].copy()
    for point in points[1:]:
        total += point
    return total / len(points)


def _vector(value):
    if hasattr(value, "x"):
        return Vector((value.x, value.y, value.z))
    return Vector((value[0], value[1], value[2]))


def _measurement_points(measurement):
    """The points of a measurement as vectors.

    ``foreach_get`` reads the whole collection in one C call. Walking it in
    Python instead costs three RNA attribute lookups per point, which the
    overlay pays for every point of every measurement it draws.
    """
    points = measurement.points
    count = len(points)
    if not count:
        return []
    try:
        flat = [0.0] * (count * 3)
        points.foreach_get("co", flat)
    except Exception:
        return [Vector((point.co[0], point.co[1], point.co[2])) for point in points]
    return [Vector(flat[offset:offset + 3]) for offset in range(0, count * 3, 3)]


def _angle_arc_points(start, center, end):
    v1 = start - center
    v2 = end - center
    len1 = v1.length
    len2 = v2.length
    if len1 <= MIN_MEASUREMENT_LENGTH or len2 <= MIN_MEASUREMENT_LENGTH:
        return ()

    radius = min(len1, len2) * 0.25
    if radius <= MIN_MEASUREMENT_LENGTH:
        return ()

    try:
        axis = v1.cross(v2)
        axis_length = axis.length
        if axis_length <= MIN_MEASUREMENT_LENGTH:
            return ()
        angle = math.acos(max(-1.0, min(1.0, v1.dot(v2) / (len1 * len2))))
        if angle <= 1.0e-6:
            return ()

        # Two unit vectors spanning the arc's plane. Sweeping a point across
        # them is what a rotation matrix would do, without building one: the
        # old loop constructed a fresh Matrix.Rotation per segment, which at a
        # few thousand plane measurements dominated the whole redraw.
        along = v1 / len1
        across = (axis / axis_length).cross(along)

        # Rotate the coefficient pair by a fixed step instead of calling cos and
        # sin per segment. Drift over this many steps is far below a pixel.
        step = angle / ANGLE_ARC_SEGMENTS
        cos_step = math.cos(step)
        sin_step = math.sin(step)
        cos_a = 1.0
        sin_a = 0.0

        arc = []
        for _step_index in range(ANGLE_ARC_SEGMENTS + 1):
            arc.append(center + along * (cos_a * radius) + across * (sin_a * radius))
            cos_a, sin_a = cos_a * cos_step - sin_a * sin_step, cos_a * sin_step + sin_a * cos_step
        return tuple(arc)
    except Exception:
        return ()


def _measurement_is_polygon(measurement, points):
    """Whether the outline closes back to its first point.

    A trace never does: it follows a fracture across a surface and its two ends
    are two ends, not a gap waiting to be joined.
    """
    kind = _measurement_kind(measurement)
    if kind == "TRACE":
        return False
    return len(points) > 3 or kind == "POLYLINE"


def _polygon_preview_points(include_current=False):
    points = list(_polygon_preview["points"])
    current = _polygon_preview["current"]
    if include_current and current is not None:
        if len(points) >= 3 and (current - points[0]).length <= MIN_MEASUREMENT_LENGTH:
            return points
        if not points or (current - points[-1]).length > MIN_MEASUREMENT_LENGTH:
            points.append(current)
    return points


def _screen_distance_to_point(context, event, point):
    from bpy_extras import view3d_utils
    from mathutils import Vector

    position = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, point)
    if position is None:
        return float("inf")
    mouse = Vector((event.mouse_region_x, event.mouse_region_y))
    return (mouse - position).length


