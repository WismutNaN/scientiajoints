def _snap_enabled(scene, event):
    snap_by_default = bool(getattr(scene, "scientia_measure_snap_by_default", False))
    return snap_by_default != bool(getattr(event, "ctrl", False))


def _cursor_for_state(ctrl, snapped, mode):
    if snapped:
        return 'EYEDROPPER'
    if ctrl:
        return 'CROSSHAIR'
    if mode in {"edit_point", "add_center"}:
        return 'MOVE_X'
    return 'CROSSHAIR'


def _set_cursor(context, cursor):
    try:
        context.window.cursor_modal_set(cursor)
    except Exception:
        pass


def _restore_cursor(context):
    try:
        context.window.cursor_modal_restore()
    except Exception:
        pass


def _tag_view3d_redraw(context):
    screen = getattr(context, "screen", None)
    if screen is None:
        return
    for area in screen.areas:
        if area.type == 'VIEW_3D':
            area.tag_redraw()
