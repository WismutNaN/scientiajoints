def _draw_point_chain(shader, batch_for_shader, points, color, closed=False):
    _draw_line_coords(shader, batch_for_shader, _point_chain_coords(points, closed=closed), color)


def _point_chain_coords(points, closed=False):
    coords = []
    if len(points) < 2:
        return coords
    for start, end in _segments(points, closed=closed):
        coords.extend((start, end))
    return coords


def _draw_line_coords(shader, batch_for_shader, coords, color):
    if not coords:
        return
    batch = batch_for_shader(shader, 'LINES', {"pos": coords})
    shader.bind()
    shader.uniform_float("color", color)
    batch.draw(shader)


def _draw_screen_handles(context, view3d_utils, shader, batch_for_shader, points, color, measurement_index, scene):
    if not points:
        return

    active_index = getattr(scene, "scientia_active_measurement_index", -1)
    hover_index, hover_part, hover_point = _active_preview["hover"]
    is_active_measurement = measurement_index == active_index or measurement_index < 0

    for point_index, point in enumerate(points):
        position = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, point)
        if position is None:
            continue

        is_hovered = (
            measurement_index == hover_index
            and hover_part == "point"
            and hover_point == point_index
        )
        size = 6.5
        if is_active_measurement:
            size = 8.0
        if is_hovered:
            size = 10.0

        if len(points) == 3 and point_index == 1:
            _draw_handle_circle_2d(shader, batch_for_shader, position, color, size, is_active_measurement, is_hovered)
        else:
            _draw_handle_square_2d(shader, batch_for_shader, position, color, size, is_active_measurement, is_hovered)


def _draw_snap_marker_2d(context, view3d_utils, shader, batch_for_shader, point, snap_type):
    position = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, point)
    if position is None:
        return

    marker_type = snap_type or "FACE"
    color = (0.2, 1.0, 0.35, 1.0)
    if marker_type == "VERTEX":
        _draw_square_outline_2d(shader, batch_for_shader, position, 8.0, (0.0, 0.0, 0.0, 0.95), 3.0)
        _draw_square_outline_2d(shader, batch_for_shader, position, 8.0, color, 1.5)
    elif marker_type == "EDGE":
        _draw_hourglass_2d(shader, batch_for_shader, position, 9.0, (0.0, 0.0, 0.0, 0.95), 3.0)
        _draw_hourglass_2d(shader, batch_for_shader, position, 9.0, color, 1.5)
    else:
        _draw_circle_outline_2d(shader, batch_for_shader, position, 8.0, (0.0, 0.0, 0.0, 0.95), 3.0)
        _draw_circle_outline_2d(shader, batch_for_shader, position, 8.0, color, 1.5)


def _draw_handle_square_2d(shader, batch_for_shader, position, color, size, active, hovered):
    fill = (1.0, 1.0, 1.0, 1.0) if hovered else color
    if active and not hovered:
        fill = (1.0, 0.9, 0.2, 1.0)

    _draw_filled_square_2d(shader, batch_for_shader, position, size + 3.5, (0.0, 0.0, 0.0, 0.85))
    _draw_filled_square_2d(shader, batch_for_shader, position, size, fill)
    _draw_square_outline_2d(shader, batch_for_shader, position, size + 0.5, (1.0, 1.0, 1.0, 0.95), 1.0)


def _draw_handle_circle_2d(shader, batch_for_shader, position, color, size, active, hovered):
    outline_color = (1.0, 1.0, 1.0, 1.0) if hovered else color
    if active and not hovered:
        outline_color = (1.0, 0.9, 0.2, 1.0)

    _draw_circle_outline_2d(shader, batch_for_shader, position, size + 2.5, (0.0, 0.0, 0.0, 0.9), 3.0)
