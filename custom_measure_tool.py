def _draw_filled_square_2d(shader, batch_for_shader, position, size, color):
    x = float(position.x)
    y = float(position.y)
    half = size * 0.5
    coords = (
        (x - half, y - half),
        (x + half, y - half),
        (x + half, y + half),
        (x - half, y + half),
    )
    indices = ((0, 1, 2), (0, 2, 3))
    batch = batch_for_shader(shader, 'TRIS', {"pos": coords}, indices=indices)
    shader.bind()
    shader.uniform_float("color", color)
    batch.draw(shader)


def _draw_square_outline_2d(shader, batch_for_shader, position, size, color, width=1.0):
    x = float(position.x)
    y = float(position.y)
    half = size * 0.5
    coords = (
        (x - half, y - half), (x + half, y - half),
        (x + half, y - half), (x + half, y + half),
        (x + half, y + half), (x - half, y + half),
        (x - half, y + half), (x - half, y - half),
    )
    _draw_2d_lines(shader, batch_for_shader, coords, color, width)


def _draw_circle_outline_2d(shader, batch_for_shader, position, radius, color, width=1.0):
    x = float(position.x)
    y = float(position.y)
    segments = 28
    coords = []
    for index in range(segments):
        angle_a = math.tau * index / segments
        angle_b = math.tau * (index + 1) / segments
        coords.append((x + math.cos(angle_a) * radius, y + math.sin(angle_a) * radius))
        coords.append((x + math.cos(angle_b) * radius, y + math.sin(angle_b) * radius))
    _draw_2d_lines(shader, batch_for_shader, coords, color, width)


def _draw_hourglass_2d(shader, batch_for_shader, position, size, color, width=1.0):
    x = float(position.x)
    y = float(position.y)
    half = size * 0.5
    coords = (
        (x - half, y + half), (x + half, y + half),
        (x - half, y + half), (x, y),
        (x + half, y + half), (x, y),
        (x - half, y - half), (x + half, y - half),
        (x - half, y - half), (x, y),
        (x + half, y - half), (x, y),
    )
    _draw_2d_lines(shader, batch_for_shader, coords, color, width)


def _draw_cross_2d(shader, batch_for_shader, position, size, color, width=1.0):
    x = float(position.x)
    y = float(position.y)
    half = size * 0.5
    coords = (
        (x - half, y), (x + half, y),
        (x, y - half), (x, y + half),
    )
    _draw_2d_lines(shader, batch_for_shader, coords, color, width)


