#: The toolbar identifiers this add-on owns. Nothing else may use them, so
#: removing an entry that carries one can never touch another add-on's tool.
TOOL_IDNAMES = (
    ScientiaMeasureWorkSpaceTool.bl_idname,
    ScientiaPolygonMeasureWorkSpaceTool.bl_idname,
    ScientiaTraceMeasureWorkSpaceTool.bl_idname,
)


def _toolbar_tool_lists():
    """Blender's per-mode tool lists for the 3D View toolbar."""
    from bl_ui.space_toolsystem_common import ToolSelectPanelHelper

    helper = ToolSelectPanelHelper._tool_class_from_space_type('VIEW_3D')
    if helper is None:
        return ()
    return tuple(helper._tools.values())


def _drop_stray_separators(tools):
    """Trim the separator entries a removal can leave behind."""
    while tools and tools[0] is None:
        del tools[0]
    while tools and tools[-1] is None:
        del tools[-1]
    for index in range(len(tools) - 1, 0, -1):
        if tools[index] is None and tools[index - 1] is None:
            del tools[index]


def _remove_tool_keymap(tool_def):
    """Remove the key-map ``register_tool`` created for a tool definition.

    After registration ``ToolDef.keymap`` is a one-item list holding the
    generated key-map name, which is what Blender's own ``unregister_tool``
    looks up. Before registration it still holds the callback, so anything
    that is not a string is left alone.
    """
    keymap = getattr(tool_def, "keymap", None)
    if not keymap or not isinstance(keymap[0], str):
        return
    keyconfigs = bpy.context.window_manager.keyconfigs
    for keyconfig in (keyconfigs.default, keyconfigs.addon):
        if keyconfig is None:
            continue
        existing = keyconfig.keymaps.get(keymap[0])
        if existing is not None:
            keyconfig.keymaps.remove(existing)


def purge_registered_tools(idnames=TOOL_IDNAMES):
    """Remove toolbar entries for ``idnames``, whoever registered them.

    ``bpy.utils.unregister_tool()`` finds the entry by the exact ``ToolDef``
    object it stored on the class as ``_bl_tool``, so it cannot remove one left
    by a *different* copy of this module. That happens when the add-on is
    installed twice, as an extension and as a legacy add-on, and when a reload
    drops the old classes from ``sys.modules`` before ``unregister()`` runs.
    Blender then refuses the fresh registration with
    ``Tool 'scientiajoints.measure' already exists!`` and the add-on fails to
    enable at all.

    Returns the identifiers that were actually removed.
    """
    # ToolDef is itself a namedtuple, so it has to be recognised before the
    # plain tuple that marks a nested group; isinstance(item, tuple) is true
    # for both, and treating a tool as a group iterates its fields instead.
    from bl_ui.space_toolsystem_common import ToolDef

    removed = []

    def keep(entry):
        if getattr(entry, "idname", None) not in idnames:
            return True
        removed.append(entry.idname)
        _remove_tool_keymap(entry)
        return False

    for tools in _toolbar_tool_lists():
        for index in range(len(tools) - 1, -1, -1):
            item = tools[index]
            if item is None:
                continue
            if isinstance(item, ToolDef):
                if not keep(item):
                    del tools[index]
            elif isinstance(item, tuple):
                kept = [sub for sub in item if sub is None or keep(sub)]
                if len(kept) == len(item):
                    continue
                _drop_stray_separators(kept)
                if kept:
                    tools[index] = tuple(kept)
                else:
                    del tools[index]
        _drop_stray_separators(tools)

    return tuple(removed)


#: Registration order in the toolbar, each tool going after the one before it.
_WORKSPACE_TOOLS = (
    ScientiaMeasureWorkSpaceTool,
    ScientiaPolygonMeasureWorkSpaceTool,
    ScientiaTraceMeasureWorkSpaceTool,
)


def register_measure_tool():
    for tool in reversed(_WORKSPACE_TOOLS):
        try:
            bpy.utils.unregister_tool(tool)
        except Exception:
            pass
    try:
        leftover = purge_registered_tools()
    except Exception as e:
        leftover = ()
        logger.debug("Could not inspect the 3D View toolbar: %s", e)
    if leftover:
        logger.warning(
            "Removed a leftover toolbar entry for %s before registering. This means an earlier "
            "ScientiaJoints registration was not cleaned up, or the add-on is installed twice - "
            "as an extension and as a legacy add-on. Keep only one installation.",
            ", ".join(sorted(set(leftover))),
        )
    try:
        bpy.utils.register_tool(ScientiaMeasureWorkSpaceTool, after={"builtin.measure"}, separator=True)
    except Exception:
        bpy.utils.register_tool(ScientiaMeasureWorkSpaceTool, after={"builtin.cursor"}, separator=True)
    previous = ScientiaMeasureWorkSpaceTool.bl_idname
    for tool in _WORKSPACE_TOOLS[1:]:
        try:
            bpy.utils.register_tool(tool, after={previous}, separator=False)
        except Exception:
            bpy.utils.register_tool(tool, after={"builtin.measure"}, separator=True)
        previous = tool.bl_idname
    ensure_measure_overlay()


def unregister_measure_tool():
    for tool in reversed(_WORKSPACE_TOOLS):
        try:
            bpy.utils.unregister_tool(tool)
        except Exception:
            pass
    # Belt and braces: an entry whose class object no longer matches survives
    # the calls above and would block the next registration.
    try:
        purge_registered_tools()
    except Exception as e:
        logger.debug("Could not clean the 3D View toolbar: %s", e)
    remove_measure_overlay()


def _mouse_to_world(context, event, depth_location=None, snap=False):
    from bpy_extras import view3d_utils
    from mathutils import Vector

    region = context.region
    rv3d = context.region_data
    coord = (event.mouse_region_x, event.mouse_region_y)

    if snap:
        origin = view3d_utils.region_2d_to_origin_3d(region, rv3d, coord)
        direction = view3d_utils.region_2d_to_vector_3d(region, rv3d, coord)
        try:
            depsgraph = context.evaluated_depsgraph_get()
            hit, location, _normal, index, obj, matrix = context.scene.ray_cast(
                depsgraph,
                origin,
                direction,
            )
            if hit:
                snap_location, snap_type = _classified_snap_location(
                    context,
                    event,
                    location,
                    obj,
                    matrix,
                    index,
                )
                return snap_location.copy(), True, snap_type
        except Exception:
            pass

    if depth_location is None:
        cursor = getattr(context.scene, "cursor", None)
        depth_location = getattr(cursor, "location", Vector((0.0, 0.0, 0.0)))

    return view3d_utils.region_2d_to_location_3d(region, rv3d, coord, depth_location), False, None


def _classified_snap_location(context, event, location, obj, matrix, polygon_index):
    from bpy_extras import view3d_utils
    from mathutils import Vector

    if obj is None or polygon_index < 0:
        return location, "FACE"

    mesh = getattr(obj, "data", None)
    if mesh is None or not hasattr(mesh, "polygons") or polygon_index >= len(mesh.polygons):
        return location, "FACE"

    world_matrix = matrix if matrix is not None else obj.matrix_world
    polygon = mesh.polygons[polygon_index]
    mouse = Vector((event.mouse_region_x, event.mouse_region_y))

    vertex_candidates = []
    for vertex_index in polygon.vertices:
        vertex = world_matrix @ mesh.vertices[vertex_index].co
        vertex_2d = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, vertex)
        if vertex_2d is None:
            continue
        vertex_candidates.append(((mouse - vertex_2d).length, vertex))

    if vertex_candidates:
        distance, vertex = min(vertex_candidates, key=lambda item: item[0])
        if distance <= SNAP_VERTEX_DISTANCE_PX:
            return vertex, "VERTEX"

    edge_candidates = []
    vertices = list(polygon.vertices)
    for index, vertex_index in enumerate(vertices):
        next_index = vertices[(index + 1) % len(vertices)]
        start = world_matrix @ mesh.vertices[vertex_index].co
        end = world_matrix @ mesh.vertices[next_index].co
        closest = _closest_point_on_segment(location, start, end)
        closest_2d = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, closest)
        if closest_2d is None:
            continue
        edge_candidates.append(((mouse - closest_2d).length, closest))

    if edge_candidates:
        distance, closest = min(edge_candidates, key=lambda item: item[0])
        if distance <= SNAP_EDGE_DISTANCE_PX:
            return closest, "EDGE"

    return location, "FACE"


def _hit_measurement_part(context, event):
    from bpy_extras import view3d_utils
    from mathutils import Vector

    scene = context.scene
    if not hasattr(scene, "scientia_measurements"):
        return (-1, None, -1)

    mouse = Vector((event.mouse_region_x, event.mouse_region_y))
    best_point = (-1, None, -1)
    best_point_distance = HANDLE_DISTANCE_PX
    best_segment = (-1, None, -1)
    best_segment_distance = PICK_DISTANCE_PX

    for index, measurement in enumerate(scene.scientia_measurements):
        if not _measurement_visible(scene, measurement, index):
            continue
        points = [_vector(point.co) for point in measurement.points]
        if len(points) < 2:
            continue

        for point_index, point in enumerate(points):
            point_2d = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, point)
            if point_2d is None:
                continue
            distance = (mouse - point_2d).length
            if distance < best_point_distance:
                best_point_distance = distance
                best_point = (index, "point", point_index)

        for segment_index, (start, end) in enumerate(_segments(points, closed=_measurement_is_polygon(measurement, points))):
            start_2d = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, start)
            end_2d = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, end)
            if start_2d is None or end_2d is None:
                continue
            distance = _distance_to_segment_2d(mouse, start_2d, end_2d)
            if distance < best_segment_distance:
                best_segment_distance = distance
                best_segment = (index, "segment", segment_index)

    if best_point[0] >= 0:
        return best_point
    return best_segment


def _set_active_measurement(scene, active_index):
    for index, measurement in enumerate(scene.scientia_measurements):
        measurement.selected = index == active_index
    scene.scientia_active_measurement_index = active_index


def _draw_measurements_3d():
    context = bpy.context
    scene = getattr(context, "scene", None)
    if scene is None or not hasattr(scene, "scientia_measurements"):
        return

    import gpu
    from gpu_extras.batch import batch_for_shader

    shader = _uniform_color_shader(gpu)
    if shader is None:
        return

    fill_alpha = scene_measure_fill_alpha(scene)

    try:
        gpu.state.blend_set('ALPHA')
        gpu.state.line_width_set(scene_measure_line_width(scene))
        gpu.state.point_size_set(7.0)
    except Exception:
        pass

    line_groups, fill_groups = _world_space_geometry(scene, fill_alpha)

    # Fills first, so the outline and the handles stay readable on top of them.
    for color, coords in fill_groups.items():
        _draw_triangle_coords(shader, batch_for_shader, coords, color)

    for color, coords in line_groups.items():
        _draw_line_coords(shader, batch_for_shader, coords, color)

    if _active_preview["points"]:
        preview_color = (1.0, 0.85, 0.15, 1.0) if not _active_preview["snap"] else (0.2, 1.0, 0.35, 1.0)
        points = list(_active_preview["points"])
        if fill_alpha > 0.0:
            _draw_triangle_coords(
                shader, batch_for_shader, _area_fill_coords(points), _fill_color(preview_color, fill_alpha)
            )
        _draw_point_chain(shader, batch_for_shader, points, preview_color)
        _draw_angle_arc(shader, batch_for_shader, points, preview_color)

    polygon_points = _polygon_preview_points(include_current=True)
    if polygon_points:
        polygon_color = (1.0, 0.85, 0.15, 1.0) if not _polygon_preview["snap"] else (0.2, 1.0, 0.35, 1.0)
        closed = _polygon_preview["closed"] and len(polygon_points) >= 3
        if fill_alpha > 0.0 and closed:
            _draw_triangle_coords(
                shader, batch_for_shader, _area_fill_coords(polygon_points), _fill_color(polygon_color, fill_alpha)
            )
        _draw_point_chain(shader, batch_for_shader, polygon_points, polygon_color, closed=closed)

    try:
        gpu.state.line_width_set(1.0)
        gpu.state.point_size_set(1.0)
        gpu.state.blend_set('NONE')
    except Exception:
        pass


def _draw_measurements_2d():
    context = bpy.context
    scene = getattr(context, "scene", None)
    if scene is None or not hasattr(scene, "scientia_measurements"):
        return

    import blf
    import gpu
    from gpu_extras.batch import batch_for_shader
    from bpy_extras import view3d_utils

    # Everything below walks every measurement, so the per-measurement lookups
    # that scan the code collection are resolved once into a map first.
    code_styles = scene_measurement_code_styles(scene)
    visible = _visible_measurements(scene, context, view3d_utils, code_styles)
    #: Point coordinates read out of the collection, shared between the handle
    #: and the label pass so the RNA reads happen once per measurement.
    points_by_index = {}

    shader = _uniform_color_shader(gpu)
    if shader is not None:
        try:
            gpu.state.blend_set('ALPHA')
            gpu.state.line_width_set(1.5)
        except Exception:
            pass

        batches = HandleBatches()
        hover = _active_preview["hover"]
        budget = _handle_point_budget(scene)

        # Gather the points first and project them in one operation. One
        # transform per measurement spends more on numpy's per-call overhead
        # than the three points it saves, and one per point is what was slow to
        # begin with.
        chosen = []
        flat_points = []
        for entry in visible:
            if len(flat_points) >= budget and not entry.always:
                break
            points = points_by_index.setdefault(entry.index, _measurement_points(entry.measurement))
            chosen.append((entry, len(flat_points), len(points)))
            flat_points.extend(points)

        positions = _project_points(context, view3d_utils, flat_points)
        for entry, start, count in chosen:
            _gather_screen_handles(
                positions[start:start + count],
                batches,
                _measurement_color(entry.measurement, entry.index, scene, code_styles),
                entry.index,
                scene,
                count,
                hover,
            )

        if _active_preview["points"]:
            preview_color = (1.0, 0.85, 0.15, 1.0) if not _active_preview["snap"] else (0.2, 1.0, 0.35, 1.0)
            preview_points = list(_active_preview["points"])
            _gather_screen_handles(
                _project_points(context, view3d_utils, preview_points),
                batches,
                preview_color,
                -1,
                scene,
                len(preview_points),
                hover,
            )

        polygon_points = _polygon_preview_points(include_current=True)
        if polygon_points:
            polygon_color = (1.0, 0.85, 0.15, 1.0) if not _polygon_preview["snap"] else (0.2, 1.0, 0.35, 1.0)
            _gather_screen_handles(
                _project_points(context, view3d_utils, polygon_points),
                batches,
                polygon_color,
                -1,
                scene,
                len(polygon_points),
                hover,
            )

        batches.draw(shader, batch_for_shader, _outline_width_scale(scene))

        if _active_preview["snap_location"] is not None:
            _draw_snap_marker_2d(
                context,
                view3d_utils,
                shader,
                batch_for_shader,
                _active_preview["snap_location"],
                _active_preview["snap_type"],
            )

        if _polygon_preview["snap_location"] is not None:
            _draw_snap_marker_2d(
                context,
                view3d_utils,
                shader,
                batch_for_shader,
                _polygon_preview["snap_location"],
                _polygon_preview["snap_type"],
            )

        try:
            gpu.state.line_width_set(1.0)
            gpu.state.blend_set('NONE')
        except Exception:
            pass

    if not getattr(scene, "scientia_measure_show_labels", True):
        return

    label_size = scene_measure_label_size(scene)
    font_id = 0
    try:
        blf.size(font_id, label_size)
    except TypeError:
        blf.size(font_id, label_size, 72)

    # Labels are gathered before anything is drawn so every background plate
    # goes out in one batch instead of one per label, and so the text can be
    # drawn after the plates without a second pass over the measurements.
    plates = []
    texts = []
    budget = _label_budget(scene)
    drawn = 0
    for entry in visible:
        if drawn >= budget and not entry.always:
            break
        points = points_by_index.setdefault(entry.index, _measurement_points(entry.measurement))
        if _gather_label(
            context, view3d_utils, blf, font_id, points,
            entry.measurement, label_size, plates, texts,
        ):
            drawn += 1

    if _active_preview["points"]:
        _gather_label(
            context, view3d_utils, blf, font_id, list(_active_preview["points"]),
            None, label_size, plates, texts,
        )

    polygon_points = _polygon_preview_points(include_current=True)
    if len(polygon_points) >= 3:
        _gather_label(
            context, view3d_utils, blf, font_id, polygon_points, None, label_size, plates, texts,
        )

    if plates:
        _draw_filled_tris_2d(plates, LABEL_BACKGROUND_COLOR)
    for x, y, line in texts:
        blf.position(font_id, x, y, 0)
        blf.draw(font_id, line)


#: Vertex lists for the world-space overlay, keyed by what they were built
#: from. See :func:`_world_space_geometry`.
_geometry_cache = {"key": None, "lines": {}, "fills": {}}

#: World-space anchors of the visible measurements, one per measurement, used to
#: cull and order them. Same lifetime as the geometry above.
_anchor_cache = {"key": None, "indices": (), "anchors": None}


def clear_geometry_cache():
    _geometry_cache["key"] = None
    _geometry_cache["lines"] = {}
    _geometry_cache["fills"] = {}
    _anchor_cache["key"] = None
    _anchor_cache["indices"] = ()
    _anchor_cache["anchors"] = None


def _geometry_cache_key(scene, fill_alpha):
    """What the world-space geometry depends on.

    Deliberately not the point coordinates: hashing every point of every
    measurement each frame would cost as much as rebuilding. Editing a
    measurement goes through the operators, which bump the revision, and every
    other input is cheap to read.
    """
    active_index = getattr(scene, "scientia_active_measurement_index", -1)
    return (
        measurement_revision(),
        len(scene.scientia_measurements),
        active_index,
        # Belt and braces for the measurement being edited: a code path that
        # moved its points without bumping the revision would otherwise leave
        # the cache stale under the user's cursor. Only the active one is
        # fingerprinted, so this stays a handful of floats however large the
        # scene is.
        _active_measurement_fingerprint(scene, active_index),
        _active_preview["hover"][0],
        round(float(fill_alpha), 4),
        bool(getattr(scene, "scientia_measure_show_linear", True)),
        bool(getattr(scene, "scientia_measure_show_planes", True)),
        bool(getattr(scene, "scientia_measure_show_traces", True)),
        bool(getattr(scene, "scientia_measure_no_code_visible", True)),
        tuple(sorted(scene_measurement_code_styles(scene).items())),
        tuple(scene_measure_default_color(scene)),
        tuple(scene_measure_active_color(scene)),
    )


def _active_measurement_fingerprint(scene, active_index):
    measurements = scene.scientia_measurements
    if active_index < 0 or active_index >= len(measurements):
        return ()
    measurement = measurements[active_index]
    return (
        getattr(measurement, "kind", ""),
        tuple(tuple(point.co) for point in measurement.points),
    )


def _world_space_geometry(scene, fill_alpha):
    """Line and fill vertices for every visible measurement, in world space.

    Rebuilt only when something it depends on changes. The 3D overlay lives in
    world space, so orbiting, panning and zooming leave every vertex exactly
    where it was; recomputing them per frame - including a polygon tessellation
    and an arc per plane - was pure waste at any scene size.
    """
    key = _geometry_cache_key(scene, fill_alpha)
    if _geometry_cache["key"] == key:
        return _geometry_cache["lines"], _geometry_cache["fills"]

    code_styles = scene_measurement_code_styles(scene)
    line_groups = {}
    fill_groups = {}
    for index, measurement in enumerate(scene.scientia_measurements):
        if not _measurement_visible(scene, measurement, index, code_styles):
            continue
        points = _measurement_points(measurement)
        color = _measurement_color(measurement, index, scene, code_styles)
        is_trace = _measurement_kind(measurement) == "TRACE"
        closed = _measurement_is_polygon(measurement, points)
        coords = line_groups.setdefault(color, [])
        coords.extend(_point_chain_coords(points, closed=closed))
        if not is_trace:
            coords.extend(_angle_arc_coords(points))
        # A trace encloses nothing, so there is no surface to shade.
        if fill_alpha > 0.0 and not is_trace:
            fill_coords = _area_fill_coords(points)
            if fill_coords:
                fill_groups.setdefault(_fill_color(color, fill_alpha), []).extend(fill_coords)

    _geometry_cache["key"] = key
    _geometry_cache["lines"] = line_groups
    _geometry_cache["fills"] = fill_groups
    return line_groups, fill_groups


#: One measurement that survived culling. ``always`` marks the ones no budget
#: may drop: the active measurement is being edited and the hovered one is
#: about to be, so their handles have to be on screen.
_VisibleMeasurement = collections.namedtuple("_VisibleMeasurement", ("index", "measurement", "always"))

#: How far outside the region a measurement may sit and still be drawn. Its
#: anchor is culled, not its points, so the margin has to cover a measurement
#: whose anchor is off screen while part of it is not.
CULL_MARGIN_PX = 200.0


def _visible_anchors(scene, code_styles):
    """Cached world-space anchors of the measurements that pass the filters.

    Returns ``(indices, anchors)`` where ``anchors`` is an ``(n, 4)`` array of
    homogeneous positions when numpy is available, else a list of vectors.
    Reading the collection and evaluating visibility is the same answer every
    frame until a measurement changes, so it is keyed on the same revision as
    the world-space geometry.
    """
    key = _anchor_cache_key(scene, code_styles)
    if _anchor_cache["key"] == key:
        return _anchor_cache["indices"], _anchor_cache["anchors"]

    indices = []
    positions = []
    for index, measurement in enumerate(scene.scientia_measurements):
        points = measurement.points
        if not len(points):
            continue
        if not _measurement_visible(scene, measurement, index, code_styles):
            continue
        coordinate = points[0].co
        indices.append(index)
        positions.append((coordinate[0], coordinate[1], coordinate[2], 1.0))

    numpy = _numpy_offsets()[0]
    anchors = numpy.array(positions, dtype="f4").reshape(-1, 4) if numpy is not None else positions

    _anchor_cache["key"] = key
    _anchor_cache["indices"] = tuple(indices)
    _anchor_cache["anchors"] = anchors
    return _anchor_cache["indices"], anchors


def _anchor_cache_key(scene, code_styles):
    return (
        measurement_revision(),
        len(scene.scientia_measurements),
        getattr(scene, "scientia_active_measurement_index", -1),
        bool(getattr(scene, "scientia_measure_show_linear", True)),
        bool(getattr(scene, "scientia_measure_show_planes", True)),
        bool(getattr(scene, "scientia_measure_show_traces", True)),
        bool(getattr(scene, "scientia_measure_no_code_visible", True)),
        tuple(sorted((name, style[1]) for name, style in code_styles.items())),
    )


def _screen_positions(region, region_data, anchors):
    """Project homogeneous world positions to region pixels, all at once.

    ``location_3d_to_region_2d`` costs a Python-level matrix multiply per call.
    One per measurement was the single most expensive thing the overlay did on
    a large scene, and it is the same arithmetic numpy does in one operation.
    Returns ``(x, y, in_front)`` arrays, or ``None`` without numpy.
    """
    numpy = _numpy_offsets()[0]
    if numpy is None or len(anchors) == 0:
        return None
    matrix = getattr(region_data, "perspective_matrix", None)
    if matrix is None:
        return None
    try:
        transform = numpy.array(matrix, dtype="f4")
    except Exception:
        return None

    clip = anchors @ transform.T
    w = clip[:, 3]
    in_front = w > 0.0
    safe_w = numpy.where(in_front, w, 1.0)
    half_width = (getattr(region, "width", 0) or 0) * 0.5
    half_height = (getattr(region, "height", 0) or 0) * 0.5
    x = half_width + half_width * (clip[:, 0] / safe_w)
    y = half_height + half_height * (clip[:, 1] / safe_w)
    return x, y, in_front


def _visible_measurements(scene, context, view3d_utils, code_styles):
    """Measurements worth drawing this frame, nearest the view centre first.

    Culling on one anchor per measurement rather than on every point is what
    keeps this linear in measurements and not in points. Ordering by distance to
    the middle of the view is what makes a budget defensible: what gets dropped
    is whatever is furthest from where the user is looking.
    """
    measurements = scene.scientia_measurements
    active_index = getattr(scene, "scientia_active_measurement_index", -1)
    hover_index = _active_preview["hover"][0]
    region = getattr(context, "region", None)
    region_data = getattr(context, "region_data", None)

    indices, anchors = _visible_anchors(scene, code_styles)
    projected = _screen_positions(region, region_data, anchors)

    if projected is None:
        return _visible_measurements_scalar(
            scene, context, view3d_utils, indices, active_index, hover_index
        )

    numpy = _numpy_offsets()[0]
    x, y, in_front = projected
    width = getattr(region, "width", 0) or 0
    height = getattr(region, "height", 0) or 0
    on_screen = (
        in_front
        & (x >= -CULL_MARGIN_PX)
        & (x <= width + CULL_MARGIN_PX)
        & (y >= -CULL_MARGIN_PX)
        & (y <= height + CULL_MARGIN_PX)
    )
    offset_x = x - width * 0.5
    offset_y = y - height * 0.5
    distance = offset_x * offset_x + offset_y * offset_y

    kept = numpy.flatnonzero(on_screen)
    order = kept[numpy.argsort(distance[kept], kind="stable")]

    # Only as many as the budgets can possibly consume. Every measurement has at
    # least two points, so the handle budget cannot reach past half its value in
    # measurements.
    wanted = _budgeted_indices(scene, indices, order.tolist(), active_index, hover_index)
    return _pick_measurements(measurements, wanted, active_index, hover_index)


def _budgeted_indices(scene, indices, order, active_index, hover_index):
    """Measurement indices to draw, in priority order and already truncated."""
    limit = max(_label_budget(scene), (_handle_point_budget(scene) + 1) // 2) + 2
    wanted = []
    seen = set()
    visible = set(indices)
    for index in (active_index, hover_index):
        if index in visible and index not in seen:
            seen.add(index)
            wanted.append(index)
    for position in order:
        if len(wanted) >= limit:
            break
        index = indices[position]
        if index not in seen:
            seen.add(index)
            wanted.append(index)
    return wanted


def _pick_measurements(measurements, wanted, active_index, hover_index):
    """Resolve indices to measurements in one pass over the collection.

    Indexing a Blender collection by integer walks it, so ``measurements[i]``
    inside a loop is quadratic: at ten thousand measurements that one line cost
    a second per redraw. Walking once and picking out what is wanted is linear.
    """
    ranks = {index: rank for rank, index in enumerate(wanted)}
    picked = [None] * len(wanted)
    for index, measurement in enumerate(measurements):
        rank = ranks.get(index)
        if rank is not None:
            picked[rank] = measurement

    return tuple(
        _VisibleMeasurement(index, measurement, index in (active_index, hover_index))
        for index, measurement in zip(wanted, picked)
        if measurement is not None
    )


def _visible_measurements_scalar(scene, context, view3d_utils, indices, active_index, hover_index):
    """Fallback for a viewport with no projection matrix, and for the tests.

    Without numpy or a region there is nothing to cull against, so this keeps
    the filtered order and lets the budgets do the limiting.
    """
    measurements = scene.scientia_measurements
    wanted = _budgeted_indices(scene, indices, range(len(indices)), active_index, hover_index)
    return _pick_measurements(measurements, wanted, active_index, hover_index)


def _project_points(context, view3d_utils, points):
    """Screen positions of ``points``, as ``(x, y)`` or ``None`` behind the view.

    Prefers one vectorised transform over a Python-level matrix multiply per
    point, which is what ``location_3d_to_region_2d`` costs per call.
    """
    region = getattr(context, "region", None)
    region_data = getattr(context, "region_data", None)
    numpy = _numpy_offsets()[0]
    matrix = getattr(region_data, "perspective_matrix", None)
    if numpy is None or matrix is None or not points:
        project = view3d_utils.location_3d_to_region_2d
        return [project(region, region_data, point) for point in points]

    homogeneous = numpy.empty((len(points), 4), dtype="f4")
    homogeneous[:, 3] = 1.0
    for row, point in enumerate(points):
        homogeneous[row, 0] = point[0]
        homogeneous[row, 1] = point[1]
        homogeneous[row, 2] = point[2]

    clip = homogeneous @ numpy.array(matrix, dtype="f4").T
    w = clip[:, 3]
    in_front = w > 0.0
    safe_w = numpy.where(in_front, w, 1.0)
    half_width = (getattr(region, "width", 0) or 0) * 0.5
    half_height = (getattr(region, "height", 0) or 0) * 0.5
    x = (half_width + half_width * (clip[:, 0] / safe_w)).tolist()
    y = (half_height + half_height * (clip[:, 1] / safe_w)).tolist()
    return [
        (x[row], y[row]) if visible else None
        for row, visible in enumerate(in_front.tolist())
    ]


def _handle_point_budget(scene):
    if not scene_measure_points_visible(scene):
        # Handles are limited to the active and hovered measurement, which the
        # ordering already puts first; a couple of measurements' worth is all
        # that can be drawn.
        return 0
    return max(0, int(getattr(scene, "scientia_measure_max_handle_points", DEFAULT_MAX_HANDLE_POINTS)))


def _label_budget(scene):
    return max(0, int(getattr(scene, "scientia_measure_max_labels", DEFAULT_MAX_LABELS)))


def _draw_point_chain(shader, batch_for_shader, points, color, closed=False):
    _draw_line_coords(shader, batch_for_shader, _point_chain_coords(points, closed=closed), color)


def _point_chain_coords(points, closed=False):
    coords = []
    if len(points) < 2:
        return coords
    for start, end in _segments(points, closed=closed):
        coords.extend((start, end))
    return coords


def _draw_line_coords(shader, batch_for_shader, coords, color):
    if not coords:
        return
    batch = batch_for_shader(shader, 'LINES', {"pos": coords})
    shader.bind()
    shader.uniform_float("color", color)
    batch.draw(shader)


def _draw_triangle_coords(shader, batch_for_shader, coords, color):
    # len(), not truthiness: coords can be a numpy array, and those refuse to
    # answer whether they are true.
    if len(coords) == 0:
        return
    batch = batch_for_shader(shader, 'TRIS', {"pos": coords})
    shader.bind()
    shader.uniform_float("color", color)
    batch.draw(shader)


def _fill_color(color, alpha):
    """The outline colour at the fill's opacity, so a fill always belongs to
    the measurement it came from."""
    red, green, blue = tuple(color)[:3]
    return (red, green, blue, alpha)


def _area_fill_coords(points):
    """Triangle corners covering the surface of an area measurement.

    Two and fewer points enclose nothing, so a linear measurement is never
    filled. Everything else is triangulated with Blender's tessellator, which
    also handles the concave outlines a traced fracture boundary produces; the
    fan is the fallback for when ``mathutils.geometry`` is unavailable, and is
    correct for the three-point plane that is the common case.
    """
    if len(points) < 3:
        return ()
    if len(points) == 3:
        return tuple(points)

    try:
        from mathutils.geometry import tessellate_polygon

        triangles = tessellate_polygon((points,))
    except Exception:
        return _fan_fill_coords(points)

    coords = []
    for triangle in triangles:
        if len(triangle) != 3:
            continue
        for corner in triangle:
            if not 0 <= corner < len(points):
                return _fan_fill_coords(points)
            coords.append(points[corner])
    return tuple(coords)


def _fan_fill_coords(points):
    coords = []
    for index in range(1, len(points) - 1):
        coords.extend((points[0], points[index], points[index + 1]))
    return tuple(coords)


class HandleBatches:
    """Handle geometry for a whole redraw, gathered before anything is drawn.

    Drawing a handle the moment it is computed cost three to four
    ``batch_for_shader`` calls per point - a dark disc, a fill, a ring and
    sometimes a mark - and each one allocates and uploads its own vertex
    buffer. At a few thousand points that is tens of thousands of draw calls a
    frame and it is the whole reason a large scene stalled. Gathering the
    geometry by colour first turns it into a handful.
    """

    def __init__(self):
        #: ``(fill colour, radius) -> [(x, y), ...]``. Only the centres are
        #: kept; the halo, the fill and the ring are the same circle at three
        #: radii, so storing vertices three times over would be wasted work.
        self.groups = {}
        self.marks = {}
        self.points = 0

    def add(self, position, fill, size, marked):
        # Indexed, not .x/.y: positions come from the vectorised projection as
        # plain pairs, and from mathutils as vectors.
        center = (float(position[0]), float(position[1]))
        radius = size * 0.5
        self.groups.setdefault((tuple(fill), radius), []).append(center)
        if marked:
            self.marks.setdefault(_contrasting_mark_color(fill), []).append((center, radius * 1.2))
        self.points += 1

    def draw(self, shader, batch_for_shader, line_width):
        if not self.groups:
            return
        try:
            self._draw(shader, batch_for_shader, line_width)
        except Exception as e:
            # The vertex arrays are numpy when numpy is present. If this build's
            # GPU module will not take one, fall back for the rest of the
            # session and draw this frame the slow way rather than not at all.
            if _numpy_offsets()[0] is None:
                raise
            logger.warning(
                "The GPU module rejected an array; the measurement overlay is falling back to "
                "slower geometry for this session: %s", e
            )
            disable_numpy_geometry()
            self._draw(shader, batch_for_shader, line_width)

    def _draw(self, shader, batch_for_shader, line_width):

        # The dark disc under the handles is what keeps them readable on pale
        # geometry, and the light ring on top keeps them readable on dark
        # geometry. Both are one colour for every handle, so each is one batch.
        halo = [(centers, radius + HANDLE_HALO_MARGIN) for (_color, radius), centers in self.groups.items()]
        _draw_triangle_coords(shader, batch_for_shader, _disc_vertices(halo), HANDLE_HALO_COLOR)

        fills = {}
        for (color, radius), centers in self.groups.items():
            fills.setdefault(color, []).append((centers, radius))
        for color, groups in fills.items():
            _draw_triangle_coords(shader, batch_for_shader, _disc_vertices(groups), color)

        rings = [(centers, radius + 0.25) for (_color, radius), centers in self.groups.items()]
        _draw_2d_lines(shader, batch_for_shader, _ring_vertices(rings), HANDLE_RING_COLOR, line_width)

        for color, marks in self.marks.items():
            coords = []
            for (x, y), size in marks:
                coords.extend(_cross_coords(x, y, size))
            _draw_2d_lines(shader, batch_for_shader, coords, color, line_width)


#: Sampled once at import. A handle is a few pixels across, so a 12-gon is
#: indistinguishable from a circle and costs a third of what 20 and 28 segments
#: did, per point, per frame.
HANDLE_CIRCLE_SEGMENTS = 12
HANDLE_HALO_COLOR = (0.0, 0.0, 0.0, 0.85)
HANDLE_RING_COLOR = (1.0, 1.0, 1.0, 0.95)
HANDLE_HALO_MARGIN = 1.75


def _unit_circle(segments):
    return tuple(
        (math.cos(math.tau * index / segments), math.sin(math.tau * index / segments))
        for index in range(segments + 1)
    )


_UNIT_CIRCLE = _unit_circle(HANDLE_CIRCLE_SEGMENTS)

#: Vertex offsets of one unit-radius handle, in the order the GPU wants them:
#: a triangle fan flattened to ``TRIS``, and a closed loop of ``LINES``.
_UNIT_FAN = tuple(
    corner
    for index in range(HANDLE_CIRCLE_SEGMENTS)
    for corner in ((0.0, 0.0), _UNIT_CIRCLE[index], _UNIT_CIRCLE[index + 1])
)
_UNIT_LOOP = tuple(
    corner
    for index in range(HANDLE_CIRCLE_SEGMENTS)
    for corner in (_UNIT_CIRCLE[index], _UNIT_CIRCLE[index + 1])
)

#: numpy versions of the two offset tables, built on first use. Blender bundles
#: numpy, and vectorising the handle geometry is worth roughly thirty times the
#: pure Python loop; the loop stays as the fallback because it is also what the
#: test suite can run, and because a GPU that refuses an array should degrade to
#: a slow overlay rather than no overlay.
_numpy_state = {"module": None, "checked": False, "fan": None, "loop": None}


def _numpy_offsets():
    """``(numpy, fan, loop)``, or ``(None, None, None)`` without numpy."""
    if not _numpy_state["checked"]:
        _numpy_state["checked"] = True
        try:
            import numpy

            _numpy_state["module"] = numpy
            _numpy_state["fan"] = numpy.array(_UNIT_FAN, dtype="f4")
            _numpy_state["loop"] = numpy.array(_UNIT_LOOP, dtype="f4")
        except Exception as e:
            logger.debug("Overlay falling back to pure Python geometry: %s", e)
    return _numpy_state["module"], _numpy_state["fan"], _numpy_state["loop"]


def disable_numpy_geometry():
    """Stop using numpy for overlay geometry for the rest of the session."""
    _numpy_state["checked"] = True
    _numpy_state["module"] = None


def _offset_vertices(groups, offsets_python, offsets_numpy_key):
    numpy, fan, loop = _numpy_offsets()
    offsets = fan if offsets_numpy_key == "fan" else loop
    if numpy is not None:
        arrays = []
        for centers, radius in groups:
            if not centers:
                continue
            base = numpy.asarray(centers, dtype="f4")
            arrays.append((base[:, None, :] + offsets * radius).reshape(-1, 2))
        if not arrays:
            return ()
        return numpy.concatenate(arrays) if len(arrays) > 1 else arrays[0]

    coords = []
    for centers, radius in groups:
        for x, y in centers:
            coords.extend((x + ox * radius, y + oy * radius) for ox, oy in offsets_python)
    return coords


def _disc_vertices(groups):
    """Triangle corners filling a circle at every centre in ``groups``.

    ``groups`` is a sequence of ``(centres, radius)`` pairs.
    """
    return _offset_vertices(groups, _UNIT_FAN, "fan")


def _ring_vertices(groups):
    """Line ends outlining a circle at every centre in ``groups``."""
    return _offset_vertices(groups, _UNIT_LOOP, "loop")


def _cross_coords(x, y, size):
    half = size * 0.5
    return [(x - half, y), (x + half, y), (x, y - half), (x, y + half)]


def _gather_screen_handles(positions, batches, color, measurement_index, scene, point_count, hover):
    """Add one measurement's handles to ``batches``.

    ``positions`` are already projected, and ``None`` for points behind the
    camera or outside the region.
    """
    active_index = getattr(scene, "scientia_active_measurement_index", -1)
    hover_index, hover_part, hover_point = hover
    is_active_measurement = measurement_index == active_index or measurement_index < 0

    base_size = scene_measure_point_size(scene)
    # Relative to the configured size, so the emphasis survives any of it.
    size = base_size if is_active_measurement else base_size * 0.8
    hovered_size = base_size * 1.25

    fill = (1.0, 0.9, 0.2, 1.0) if is_active_measurement else tuple(color)
    hovered_fill = (1.0, 1.0, 1.0, 1.0)

    for point_index, position in enumerate(positions):
        if position is None:
            continue
        is_hovered = (
            measurement_index == hover_index
            and hover_part == "point"
            and hover_point == point_index
        )
        batches.add(
            position,
            hovered_fill if is_hovered else fill,
            hovered_size if is_hovered else size,
            # The middle point of a three-point plane is the one the other two
            # hinge on, so it keeps a mark that tells it apart from an endpoint.
            marked=point_count == 3 and point_index == 1,
        )


def _draw_snap_marker_2d(context, view3d_utils, shader, batch_for_shader, point, snap_type):
    position = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, point)
    if position is None:
        return

    marker_type = snap_type or "FACE"
    color = (0.2, 1.0, 0.35, 1.0)
    if marker_type == "VERTEX":
        _draw_square_outline_2d(shader, batch_for_shader, position, 8.0, (0.0, 0.0, 0.0, 0.95), 3.0)
        _draw_square_outline_2d(shader, batch_for_shader, position, 8.0, color, 1.5)
    elif marker_type == "EDGE":
        _draw_hourglass_2d(shader, batch_for_shader, position, 9.0, (0.0, 0.0, 0.0, 0.95), 3.0)
        _draw_hourglass_2d(shader, batch_for_shader, position, 9.0, color, 1.5)
    else:
        _draw_circle_outline_2d(shader, batch_for_shader, position, 8.0, (0.0, 0.0, 0.0, 0.95), 3.0)
        _draw_circle_outline_2d(shader, batch_for_shader, position, 8.0, color, 1.5)


def _outline_width_scale(scene):
    """How much thicker than default the outlines around handles should be.

    The line width setting is in pixels for the 3D lines it was made for;
    handles carry several nested outlines whose relative weights have to stay
    intact, so they scale by the same factor instead of taking the value.
    """
    return scene_measure_line_width(scene) / DEFAULT_LINE_WIDTH


def _contrasting_mark_color(fill):
    """Black or white, whichever stays visible on ``fill``.

    The hinge mark sits on top of the handle, and the handle changes colour
    with the code group, the active measurement and the hover, so a fixed mark
    colour disappears against one of them.
    """
    red, green, blue = tuple(fill)[:3]
    luminance = 0.2126 * red + 0.7152 * green + 0.0722 * blue
    return (0.0, 0.0, 0.0, 0.9) if luminance > 0.5 else (1.0, 1.0, 1.0, 0.95)


def _draw_square_outline_2d(shader, batch_for_shader, position, size, color, width=1.0):
    x = float(position.x)
    y = float(position.y)
    half = size * 0.5
    coords = (
        (x - half, y - half), (x + half, y - half),
        (x + half, y - half), (x + half, y + half),
        (x + half, y + half), (x - half, y + half),
        (x - half, y + half), (x - half, y - half),
    )
    _draw_2d_lines(shader, batch_for_shader, coords, color, width)


def _draw_circle_outline_2d(shader, batch_for_shader, position, radius, color, width=1.0):
    x = float(position.x)
    y = float(position.y)
    segments = 28
    coords = []
    for index in range(segments):
        angle_a = math.tau * index / segments
        angle_b = math.tau * (index + 1) / segments
        coords.append((x + math.cos(angle_a) * radius, y + math.sin(angle_a) * radius))
        coords.append((x + math.cos(angle_b) * radius, y + math.sin(angle_b) * radius))
    _draw_2d_lines(shader, batch_for_shader, coords, color, width)


def _draw_hourglass_2d(shader, batch_for_shader, position, size, color, width=1.0):
    x = float(position.x)
    y = float(position.y)
    half = size * 0.5
    coords = (
        (x - half, y + half), (x + half, y + half),
        (x - half, y + half), (x, y),
        (x + half, y + half), (x, y),
        (x - half, y - half), (x + half, y - half),
        (x - half, y - half), (x, y),
        (x + half, y - half), (x, y),
    )
    _draw_2d_lines(shader, batch_for_shader, coords, color, width)


def _draw_cross_2d(shader, batch_for_shader, position, size, color, width=1.0):
    x = float(position.x)
    y = float(position.y)
    half = size * 0.5
    coords = (
        (x - half, y), (x + half, y),
        (x, y - half), (x, y + half),
    )
    _draw_2d_lines(shader, batch_for_shader, coords, color, width)


def _draw_2d_lines(shader, batch_for_shader, coords, color, width=1.0):
    import gpu

    if len(coords) == 0:
        return
    try:
        gpu.state.line_width_set(width)
    except Exception:
        pass
    batch = batch_for_shader(shader, 'LINES', {"pos": coords})
    shader.bind()
    shader.uniform_float("color", color)
    batch.draw(shader)


def _draw_angle_arc(shader, batch_for_shader, points, color):
    _draw_line_coords(shader, batch_for_shader, _angle_arc_coords(points), color)


def _angle_arc_coords(points):
    if len(points) != 3:
        return []
    arc_points = _angle_arc_points(points[0], points[1], points[2])
    if len(arc_points) < 2:
        return []
    coords = []
    for index in range(len(arc_points) - 1):
        coords.extend((arc_points[index], arc_points[index + 1]))
    return coords


def _gather_label(
    context, view3d_utils, blf, font_id, points, measurement, label_size, plates, texts,
):
    """Work out one label's plate and text placement without drawing it.

    Every plate shares one colour, so collecting them lets the whole overlay's
    label backgrounds go out as a single batch instead of one per label.
    Returns whether a label was placed, which is what the budget counts.
    """
    if len(points) < 2:
        return False
    label, anchor = _measurement_label(points, context.scene, measurement)
    if not label:
        return False
    position = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, anchor)
    if position is None:
        return False

    lines = str(label).splitlines()
    line_height = _label_line_height(label_size)
    widths = _label_line_widths(blf, font_id, lines, label_size)
    block = _label_block(position, widths, len(lines), line_height)

    if getattr(context.scene, "scientia_measure_label_background", True):
        plates.extend(_label_background_coords(block, line_height))

    # The block is centred on the measurement, and every line is centred in the
    # block, so the label reads as belonging to the point it names rather than
    # hanging off one corner of it.
    for line_index, line in enumerate(lines):
        left = block.center_x - widths[line_index] * 0.5
        baseline = block.top - (line_index + LABEL_BASELINE_OFFSET) * line_height
        texts.append((left, baseline, line))
    return True


