class ScientiaMeasureDragOperator(Operator):
    bl_idname = "wm.scientia_measure_drag"
    bl_label = "Scientia Measure Drag"
    bl_description = "Create or edit a ScientiaJoints measurement"
    bl_options = {'UNDO'}

    def invoke(self, context, event):
        if context.area.type != 'VIEW_3D':
            return {'PASS_THROUGH'}

        ensure_measure_overlay()
        ensure_default_scene_measure_layer(context.scene)
        self._mode = None
        self._measure_index = -1
        self._point_index = -1
        self._start_location = None
        self._depth_location = None
        self._drag_started = False
        self._mouse_start = (event.mouse_region_x, event.mouse_region_y)

        hit = _hit_measurement_part(context, event)
        _active_preview["hover"] = hit

        if hit[0] >= 0:
            active_index = getattr(context.scene, "scientia_active_measurement_index", -1)
            is_active_measurement = hit[0] == active_index
            _set_active_measurement(context.scene, hit[0])
            measurement = context.scene.scientia_measurements[hit[0]]
            points = [_vector(point) for point in scene_measurement_points(measurement)]

            if not is_active_measurement:
                self._mode = "select"
                self._measure_index = hit[0]
                self._depth_location = _average_point(points)
            elif hit[1] == "point":
                self._mode = "edit_point"
                self._measure_index = hit[0]
                self._point_index = hit[2]
                self._depth_location = points[hit[2]]
            elif hit[1] == "segment" and len(points) == 2:
                self._mode = "add_center"
                self._measure_index = hit[0]
                self._point_index = 1
                self._depth_location = (points[0] + points[1]) * 0.5
                _active_preview["points"] = (points[0], self._depth_location, points[1])
            else:
                self._mode = "select"
                self._measure_index = hit[0]
                self._depth_location = _average_point(points)
        else:
            snap = _snap_enabled(context.scene, event)
            point, snapped, snap_type = _mouse_to_world(context, event, None, snap)
            self._mode = "new"
            self._start_location = point
            self._depth_location = point
            _active_preview["points"] = (point, point)
            _active_preview["snap"] = snapped
            _active_preview["snap_type"] = snap_type
            _active_preview["snap_location"] = point if snapped else None

        _set_cursor(context, _cursor_for_state(_snap_enabled(context.scene, event), _active_preview["snap"], self._mode))
        context.window_manager.modal_handler_add(self)
        context.area.tag_redraw()
        return {'RUNNING_MODAL'}

    def modal(self, context, event):
        if context.area:
            context.area.tag_redraw()

        if event.type in {'ESC', 'RIGHTMOUSE'}:
            _reset_preview()
            _restore_cursor(context)
            return {'CANCELLED'}

        if event.type == 'MOUSEMOVE':
            self._handle_mousemove(context, event)
            return {'RUNNING_MODAL'}

        if event.type == 'LEFTMOUSE' and event.value == 'RELEASE':
            self._handle_release(context, event)
            _reset_preview()
            _restore_cursor(context)
            return {'FINISHED'}

        return {'PASS_THROUGH'}

    def _handle_mousemove(self, context, event):
        self._drag_started = True
        if self._mode == "select":
            _set_cursor(context, _cursor_for_state(_snap_enabled(context.scene, event), False, self._mode))
            return

        snap = _snap_enabled(context.scene, event)
        point, snapped, snap_type = _mouse_to_world(context, event, self._depth_location, snap)
        _active_preview["snap"] = snapped
        _active_preview["snap_type"] = snap_type
        _active_preview["snap_location"] = point if snapped else None
        _set_cursor(context, _cursor_for_state(snap, snapped, self._mode))

        if self._mode == "new":
            _active_preview["points"] = (self._start_location, point)
            return

        if self._mode == "edit_point":
            self._preview_existing_point(context, point)
            return

        if self._mode == "add_center":
            if 0 <= self._measure_index < len(context.scene.scientia_measurements):
                measurement = context.scene.scientia_measurements[self._measure_index]
                base = [_vector(item) for item in scene_measurement_points(measurement)]
                if len(base) == 2:
                    _active_preview["points"] = (base[0], point, base[1])

    def _handle_release(self, context, event):
        if self._mode == "select":
            return

        snap = _snap_enabled(context.scene, event)
        point, snapped, snap_type = _mouse_to_world(context, event, self._depth_location, snap)
        _active_preview["snap"] = snapped
        _active_preview["snap_type"] = snap_type
        _active_preview["snap_location"] = point if snapped else None

        if self._mode == "new":
            # A short click on empty space deselects instead of creating a
            # degenerate micro-measurement from cursor jitter.
            moved_px = math.hypot(
                event.mouse_region_x - self._mouse_start[0],
                event.mouse_region_y - self._mouse_start[1],
            )
            if moved_px < CLICK_SELECT_THRESHOLD_PX:
                _set_active_measurement(context.scene, -1)
                return
            if (_vector(point) - _vector(self._start_location)).length > MIN_MEASUREMENT_LENGTH:
                add_scene_measurement(context.scene, (self._start_location, point))
            return

        if self._mode == "edit_point":
            if 0 <= self._measure_index < len(context.scene.scientia_measurements):
                measurement = context.scene.scientia_measurements[self._measure_index]
                points = list(scene_measurement_points(measurement))
                if 0 <= self._point_index < len(points):
                    points[self._point_index] = point
                    set_scene_measurement_points(measurement, points)
                    _set_active_measurement(context.scene, self._measure_index)
            return

        if self._mode == "add_center":
            if 0 <= self._measure_index < len(context.scene.scientia_measurements):
                measurement = context.scene.scientia_measurements[self._measure_index]
                base = [_vector(item) for item in scene_measurement_points(measurement)]
                if len(base) == 2:
                    set_scene_measurement_points(measurement, (base[0], point, base[1]))
                    _set_active_measurement(context.scene, self._measure_index)

    def _preview_existing_point(self, context, point):
        if not (0 <= self._measure_index < len(context.scene.scientia_measurements)):
            return
        measurement = context.scene.scientia_measurements[self._measure_index]
        points = [_vector(item) for item in scene_measurement_points(measurement)]
        if not (0 <= self._point_index < len(points)):
            return
        points[self._point_index] = point
        _active_preview["points"] = tuple(points)


class ScientiaPolygonMeasureOperator(Operator):
    bl_idname = "wm.scientia_polygon_measure"
    bl_label = "Scientia Polygon Plane"
    bl_description = "Create a closed multi-point polygon plane measurement"
    bl_options = {'UNDO'}

    def invoke(self, context, event):
        if context.area.type != 'VIEW_3D':
            return {'PASS_THROUGH'}

        ensure_measure_overlay()
        ensure_default_scene_measure_layer(context.scene)
        _reset_preview()
        _reset_polygon_preview()
        self._mode = "create"
        self._measure_index = -1
        self._point_index = -1
        self._points = []
        self._depth_location = None

        hit = _hit_measurement_part(context, event)
        if hit[0] >= 0:
            active_index = getattr(context.scene, "scientia_active_measurement_index", -1)
            is_active_measurement = hit[0] == active_index
            _set_active_measurement(context.scene, hit[0])
            if not is_active_measurement or hit[1] != "point":
                context.area.tag_redraw()
                return {'FINISHED'}
            measurement = context.scene.scientia_measurements[hit[0]]
            points = [_vector(point) for point in scene_measurement_points(measurement)]
            if not (0 <= hit[2] < len(points)):
                context.area.tag_redraw()
                return {'FINISHED'}
            self._mode = "edit_point"
            self._measure_index = hit[0]
            self._point_index = hit[2]
            self._depth_location = points[hit[2]]
            _active_preview["points"] = tuple(points)
            _active_preview["hover"] = hit
            context.window_manager.modal_handler_add(self)
            context.area.tag_redraw()
            return {'RUNNING_MODAL'}

        self._add_point(context, event)
        context.window_manager.modal_handler_add(self)
        context.area.tag_redraw()
        return {'RUNNING_MODAL'}

    def modal(self, context, event):
        if context.area:
            context.area.tag_redraw()

        if event.type == 'ESC':
            _reset_polygon_preview()
            _reset_preview()
            _restore_cursor(context)
            return {'CANCELLED'}

        if event.type == 'RIGHTMOUSE':
            if event.value != 'PRESS':
                return {'RUNNING_MODAL'}
            # Right click finishes the polygon so the user does not have to
            # find the first point again; with too few points it cancels.
            if self._mode == "create" and len(self._points) >= 3:
                return self._finish(context)
            _reset_polygon_preview()
            _reset_preview()
            _restore_cursor(context)
            return {'CANCELLED'}

        if event.type in {'MIDDLEMOUSE', 'WHEELUPMOUSE', 'WHEELDOWNMOUSE', 'WHEELINMOUSE', 'WHEELOUTMOUSE'}:
            return {'PASS_THROUGH'}

        if event.type in {'RET', 'NUMPAD_ENTER', 'SPACE'} and event.value == 'PRESS':
            return self._finish(context)

        if event.type in {'BACK_SPACE', 'X', 'DEL'} and event.value == 'PRESS':
            if self._mode == "create":
                self._remove_last_point(context)
            return {'RUNNING_MODAL'}

        if event.type == 'MOUSEMOVE':
            if self._mode == "edit_point":
                self._preview_existing_point(context, event)
                return {'RUNNING_MODAL'}
            self._update_current(context, event)
            return {'RUNNING_MODAL'}

        if self._mode == "edit_point" and event.type == 'LEFTMOUSE' and event.value == 'RELEASE':
            self._commit_existing_point(context, event)
            _reset_preview()
            _restore_cursor(context)
            return {'FINISHED'}

        if self._mode == "edit_point":
            return {'RUNNING_MODAL'}

        if event.type == 'LEFTMOUSE' and event.value == 'PRESS':
            self._update_current(context, event)
            if _polygon_preview["closing"]:
                return self._finish(context)
            self._add_point(context, event)
            return {'RUNNING_MODAL'}

        return {'PASS_THROUGH'}

    def _add_point(self, context, event):
        point, snapped, snap_type = self._event_point(context, event)
        if self._points and (point - self._points[-1]).length <= MIN_MEASUREMENT_LENGTH:
            return
        self._points.append(point)
        self._depth_location = point
        _polygon_preview["points"] = tuple(self._points)
        _polygon_preview["current"] = point
        _polygon_preview["snap"] = snapped
        _polygon_preview["snap_type"] = snap_type
        _polygon_preview["snap_location"] = point if snapped else None
        _polygon_preview["closing"] = False
        _set_cursor(context, _cursor_for_state(_snap_enabled(context.scene, event), snapped, "polygon"))

    def _update_current(self, context, event):
        point, snapped, snap_type = self._event_point(context, event)
        closing = len(self._points) >= 3 and _screen_distance_to_point(context, event, self._points[0]) <= HANDLE_DISTANCE_PX
        if closing:
            point = self._points[0]
        _polygon_preview["points"] = tuple(self._points)
        _polygon_preview["current"] = point
        _polygon_preview["snap"] = snapped
        _polygon_preview["snap_type"] = snap_type
        _polygon_preview["snap_location"] = point if snapped else None
        _polygon_preview["closing"] = closing
        _set_cursor(context, _cursor_for_state(_snap_enabled(context.scene, event), snapped or closing, "polygon"))

    def _preview_existing_point(self, context, event):
        if not (0 <= self._measure_index < len(context.scene.scientia_measurements)):
            return
        measurement = context.scene.scientia_measurements[self._measure_index]
        points = [_vector(point) for point in scene_measurement_points(measurement)]
        if not (0 <= self._point_index < len(points)):
            return
        point, snapped, snap_type = self._event_point(context, event)
        points[self._point_index] = point
        _active_preview["points"] = tuple(points)
        _active_preview["snap"] = snapped
        _active_preview["snap_type"] = snap_type
        _active_preview["snap_location"] = point if snapped else None
        _set_cursor(context, _cursor_for_state(_snap_enabled(context.scene, event), snapped, "edit_point"))

    def _commit_existing_point(self, context, event):
        if not (0 <= self._measure_index < len(context.scene.scientia_measurements)):
            return
        measurement = context.scene.scientia_measurements[self._measure_index]
        points = list(scene_measurement_points(measurement))
        if not (0 <= self._point_index < len(points)):
            return
        point, snapped, snap_type = self._event_point(context, event)
        points[self._point_index] = point
        set_scene_measurement_points(measurement, points)
        _active_preview["snap"] = snapped
        _active_preview["snap_type"] = snap_type
        _active_preview["snap_location"] = point if snapped else None
        _set_active_measurement(context.scene, self._measure_index)

    def _event_point(self, context, event):
        snap = _snap_enabled(context.scene, event)
        depth = self._depth_location
        if depth is None and self._points:
            depth = self._points[-1]
        return _mouse_to_world(context, event, depth, snap)

    def _remove_last_point(self, context):
        if self._points:
            self._points.pop()
        if not self._points:
            _reset_polygon_preview()
            _restore_cursor(context)
            return
        self._depth_location = self._points[-1]
        _polygon_preview["points"] = tuple(self._points)
        _polygon_preview["current"] = self._points[-1]
        _polygon_preview["closing"] = False

    def _finish(self, context):
        if len(self._points) < 3:
            self.report({'WARNING'}, "At least three polygon points are required.")
            _reset_polygon_preview()
            _restore_cursor(context)
            return {'CANCELLED'}
        add_scene_measurement(context.scene, tuple(self._points), kind="POLYLINE")
        _reset_polygon_preview()
        _restore_cursor(context)
        _tag_view3d_redraw(context)
        return {'FINISHED'}


