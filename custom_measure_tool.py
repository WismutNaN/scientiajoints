def _draw_angle_arc(shader, batch_for_shader, points, color):
    _draw_line_coords(shader, batch_for_shader, _angle_arc_coords(points), color)


def _angle_arc_coords(points):
    if len(points) != 3:
        return []
    arc_points = _angle_arc_points(points[0], points[1], points[2])
    if len(arc_points) < 2:
        return []
    coords = []
    for index in range(len(arc_points) - 1):
        coords.extend((arc_points[index], arc_points[index + 1]))
    return coords


def _draw_label(context, view3d_utils, blf, font_id, points, measurement=None):
    if len(points) < 2:
        return
    label, anchor = _measurement_label(points, context.scene, measurement)
    if not label:
        return
    position = view3d_utils.location_3d_to_region_2d(context.region, context.region_data, anchor)
    if position is None:
        return
    lines = str(label).splitlines()
    text_x = position.x + 6
    text_y = position.y + 6
    if getattr(context.scene, "scientia_measure_label_background", True):
        _draw_label_background_2d(blf, font_id, lines, text_x, text_y)
    for line_index, line in enumerate(lines):
        blf.position(font_id, text_x, text_y - line_index * 14, 0)
        blf.draw(font_id, line)


def _measurement_label(points, scene=None, measurement=None):
    if len(points) == 2:
        start, end = points
        return "\n".join(_linear_label_lines(points, scene, measurement)), (start + end) * 0.5
    if len(points) >= 3:
        anchor = points[1] if len(points) == 3 else _average_point(list(points))
        return "\n".join(_plane_label_lines(tuple(points), scene, measurement)), anchor
    return "", None


def _linear_label_lines(points, scene, measurement):
    lines = _metadata_label_lines(scene, measurement)
    start, end = points[:2]
    record = active_linear_record_from_points(points, scene, measurement) if scene is not None else None

    length = record.length if record is not None else (end - start).length
    line = record.line_orientation if record is not None else None
    dx = end.x - start.x
    dy = end.y - start.y
    dz = end.z - start.z
    horizontal = math.sqrt(dx * dx + dy * dy)

    if _label_enabled(scene, "scientia_label_linear_distance", True):
        lines.append(f"distance {length:.3f}")
    if line is not None and _label_enabled(scene, "scientia_label_linear_angle", False):
        lines.append(f"angle {line.dip:.1f}")
    if line is not None and _label_enabled(scene, "scientia_label_linear_azimuth", False):
        lines.append(f"az {line.rotated_azimuth:.1f}")
    if line is not None and _label_enabled(scene, "scientia_label_linear_raw_azimuth", False):
        lines.append(f"raw az {line.azimuth:.1f}")
    if _label_enabled(scene, "scientia_label_linear_dx", False):
        lines.append(f"dx {dx:.3f}")
    if _label_enabled(scene, "scientia_label_linear_dy", False):
        lines.append(f"dy {dy:.3f}")
    if _label_enabled(scene, "scientia_label_linear_dz", False):
        lines.append(f"dz {dz:.3f}")
    if _label_enabled(scene, "scientia_label_linear_horizontal", False):
        lines.append(f"horizontal {horizontal:.3f}")
    return lines


def _plane_label_lines(points, scene, measurement):
    lines = _metadata_label_lines(scene, measurement)
    record = active_plane_record_from_points(points, scene, measurement) if scene is not None else None
    plane = record.plane_orientation if record is not None else None

    if plane is not None:
        show_dip = _label_enabled(scene, "scientia_label_plane_dip", True)
        show_azimuth = _label_enabled(scene, "scientia_label_plane_azimuth", True)
        if show_dip and show_azimuth:
            lines.append(f"dip {plane.dip:.1f} az {plane.rotated_azimuth:.1f}")
        elif show_dip:
            lines.append(f"dip {plane.dip:.1f}")
        elif show_azimuth:
            lines.append(f"az {plane.rotated_azimuth:.1f}")
        if _label_enabled(scene, "scientia_label_plane_raw_azimuth", False):
            lines.append(f"raw az {plane.azimuth:.1f}")

    if _label_enabled(scene, "scientia_label_plane_angle", False):
        if record is not None and record.degree is not None:
            lines.append(f"angle {record.degree:.1f} deg")
        elif record is None:
            lines.append(f"angle {_point_angle_degrees(points):.1f} deg")
    if record is not None and _label_enabled(scene, "scientia_label_plane_area", False):
        lines.append(f"area {record.area:.4f}")
    if (
        record is not None
        and len(points) > 3
        and record.fit_error is not None
        and _label_enabled(scene, "scientia_label_plane_fit_error", True)
    ):
        lines.append(
            f"fit err {record.fit_error:.3f} ({record.fit_error_relative * 100:.1f}%)"
        )
    return lines


def _metadata_label_lines(scene, measurement):
    if scene is None or measurement is None:
        return []

    lines = []
    if _label_enabled(scene, "scientia_label_show_code", False):
        code = (getattr(measurement, "code", "") or "").strip()
        lines.append(f"code {code or 'no code'}")
    if _label_enabled(scene, "scientia_label_show_name", False):
        name = (getattr(measurement, "name", "") or "").strip()
        if name:
            lines.append(f"name {name}")
    if _label_enabled(scene, "scientia_label_show_description", False):
        description = (getattr(measurement, "description", "") or "").strip()
        if description:
            lines.append(description)
    return lines


def _label_enabled(scene, property_name, default):
    if scene is None:
        return default
    return bool(getattr(scene, property_name, default))


def _point_angle_degrees(points):
    try:
        start, center, end = points[:3]
        return math.degrees((start - center).angle(end - center))
    except Exception:
        return 0.0


def _draw_label_background_2d(blf, font_id, lines, x, y):
    if not lines:
        return
    try:
        widths = [blf.dimensions(font_id, line)[0] for line in lines]
    except Exception:
        widths = [len(line) * 7 for line in lines]
    width = max(widths, default=0.0) + 8
    height = len(lines) * 14 + 4
    _draw_filled_rect_2d(x - 4, y - height + 10, width, height, (0.05, 0.05, 0.05, 0.62))


def _draw_filled_rect_2d(x, y, width, height, color):
    import gpu
    from gpu_extras.batch import batch_for_shader

    shader = _uniform_color_shader(gpu)
    if shader is None:
        return
    coords = (
        (x, y),
        (x + width, y),
        (x + width, y + height),
        (x, y + height),
    )
    indices = ((0, 1, 2), (0, 2, 3))
    try:
        gpu.state.blend_set('ALPHA')
    except Exception:
        pass
    batch = batch_for_shader(shader, 'TRIS', {"pos": coords}, indices=indices)
    shader.bind()
    shader.uniform_float("color", color)
    batch.draw(shader)


def active_measurement_record(scene):
    try:
        index = getattr(scene, "scientia_active_measurement_index", -1)
        if index < 0 or index >= len(scene.scientia_measurements):
            return None
        measurement = scene.scientia_measurements[index]
        points = [_vector(point.co) for point in measurement.points]
        if len(points) == 2:
            return active_linear_record_from_points(points, scene, measurement)
        if len(points) >= 3:
            return active_plane_record_from_points(points, scene, measurement)
    except Exception:
        return None
    return None


def _record_cache_key(kind, points, scene, measurement):
    return (
        kind,
        tuple((float(point.x), float(point.y), float(point.z)) for point in points),
        float(getattr(scene, "az_real", 0.0)),
        float(getattr(scene, "az_model", 0.0)),
        getattr(measurement, "layer", "Default"),
    )


def _cached_record(key, factory):
    """Memoize processed records used by the viewport overlay.

    Labels are rebuilt on every viewport redraw, and a plane record runs an
    iterative eigen decomposition, so an unmemoized overlay cost one solve per
    polygon per frame.
    """
    record = _record_cache.get(key)
    if record is not None:
        return record
    record = factory()
    if record is not None:
        if len(_record_cache) >= RECORD_CACHE_LIMIT:
            _record_cache.clear()
        _record_cache[key] = record
    return record


def clear_record_cache():
    _record_cache.clear()


def active_linear_record_from_points(points, scene, measurement):
    try:
        key = _record_cache_key("linear", points[:2], scene, measurement)
    except Exception:
        key = None

    def _build():
        try:
            raw = RawMeasurement(
                kind=MeasurementKind.LINEAR,
                points=tuple(Point3D(point.x, point.y, point.z) for point in points[:2]),
                source="ScientiaScene",
                source_id=getattr(measurement, "uuid", ""),
                layer=getattr(measurement, "layer", "Default"),
            )
            correction = AzimuthCorrection(
                az_real=getattr(scene, "az_real", 0.0),
                az_model=getattr(scene, "az_model", 0.0),
            )
            return process_linear_measurement(raw, correction)
        except Exception:
            return None

    return _build() if key is None else _cached_record(key, _build)


