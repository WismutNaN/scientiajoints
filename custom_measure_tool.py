def draw_tool_header(context, layout, with_actions=False):
    """The row of settings every ScientiaJoints tool shows in the tool header.

    Shared so the three tools cannot end up offering different toggles, which
    is what happened while each one drew its own copy.
    """
    scene = getattr(context, "scene", None)
    if scene is None:
        return
    if hasattr(scene, "scientia_measure_show_labels"):
        layout.prop(scene, "scientia_measure_show_labels", text="Labels")
    if hasattr(scene, "scientia_measure_snap_by_default"):
        layout.prop(scene, "scientia_measure_snap_by_default", text="Snap")
    for property_name, icon in (
        ("scientia_measure_show_linear", LINEAR_ICON),
        ("scientia_measure_show_planes", PLANE_ICON),
        ("scientia_measure_show_traces", TRACE_ICON),
    ):
        if hasattr(scene, property_name):
            layout.prop(scene, property_name, text="", icon=icon, toggle=True)
    if with_actions:
        layout.operator("wm.scientia_measure_deselect", text="", icon="RESTRICT_SELECT_ON")
        layout.operator("wm.scientia_measure_delete_active", text="", icon="TRASH")


def tool_icon(name):
    """Path Blender should load a workspace tool icon from.

    ``ToolSelectPanelHelper`` resolves ``bl_icon`` with
    ``os.path.join(<blender datafiles>/icons, bl_icon + ".dat")``, and
    ``os.path.join`` discards the first argument when the second is absolute.
    Returning an absolute path without the extension is therefore how an add-on
    ships its own toolbar icons.
    """
    path = os.path.join(ICON_DIRECTORY, name)
    return path if os.path.isfile(path + ".dat") else FALLBACK_TOOL_ICON


